"""
S2 — Views da produção ambulatorial SUS (BPA + competência).
===========================================================
DRF viewsets for the SUS faturamento surface, mounted under
``/api/v1/billing/`` alongside the TISS routes but gated by the SEPARATE
``sus.read`` / ``sus.write`` namespace (never ``billing.*``).

  * ``sus-competencias/`` — CRUD (``?establishment=&status=``); custom actions
    ``gerar-producao`` (the ambulatorial bridge — competência fechada → 409) and
    ``fechar`` (aberta → fechada).
  * ``bpa-consolidado/`` — manual BPA-C entry + list (``?competencia=``).
  * ``bpa-individualizado/`` — read-only list (``?competencia=``); rows are
    generated by ``gerar-producao``.
"""

from __future__ import annotations

from django.core.exceptions import ValidationError as DjangoValidationError
from drf_spectacular.types import OpenApiTypes
from drf_spectacular.utils import OpenApiParameter, extend_schema, extend_schema_view
from rest_framework import status as http_status
from rest_framework import viewsets
from rest_framework.decorators import action
from rest_framework.permissions import IsAuthenticated
from rest_framework.response import Response

from apps.billing.serializers_sus import (
    BpaConsolidadoSerializer,
    BpaIndividualizadoSerializer,
    SusCompetenciaSerializer,
)
from apps.billing.services.sus_production import gerar_producao_ambulatorial
from apps.billing.sus_models import BpaConsolidado, BpaIndividualizado, SusCompetencia
from apps.core.permissions import HasPermission

_ESTABLISHMENT_PARAM = OpenApiParameter(
    "establishment", OpenApiTypes.INT, description="Filtra por estabelecimento (Facility id)."
)
_STATUS_PARAM = OpenApiParameter(
    "status", OpenApiTypes.STR, description="Filtra por situação (aberta/fechada/exportada)."
)
_COMPETENCIA_PARAM = OpenApiParameter(
    "competencia", OpenApiTypes.INT, description="Filtra por competência (SusCompetencia id)."
)


class _SusPermissionMixin:
    """Read (``list``/``retrieve``) = ``sus.read``; everything else = ``sus.write``."""

    def get_permissions(self):
        read_actions = {"list", "retrieve"}
        permission = "sus.read" if self.action in read_actions else "sus.write"
        return [IsAuthenticated(), HasPermission(permission)]


@extend_schema_view(
    list=extend_schema(
        tags=["sus"],
        summary="Lista competências SUS",
        parameters=[_ESTABLISHMENT_PARAM, _STATUS_PARAM],
    ),
)
class SusCompetenciaViewSet(_SusPermissionMixin, viewsets.ModelViewSet):
    """Competências SUS (janela mensal de faturamento). Read=sus.read / write=sus.write."""

    serializer_class = SusCompetenciaSerializer

    def get_queryset(self):
        qs = SusCompetencia.objects.all().order_by("-competencia")
        establishment = self.request.query_params.get("establishment")
        if establishment:
            qs = qs.filter(establishment_id=establishment)
        status_ = self.request.query_params.get("status")
        if status_:
            qs = qs.filter(status=status_)
        return qs

    def perform_create(self, serializer):
        serializer.save(created_by=self.request.user)

    @extend_schema(
        tags=["sus"],
        summary="Gera produção ambulatorial (BPA-I) da competência",
        request=None,
        responses={200: OpenApiTypes.OBJECT},
    )
    @action(detail=True, methods=["post"], url_path="gerar-producao")
    def gerar_producao(self, request, pk=None):
        """Bridge ambulatorial: cria BPA-I dos EncounterProcedures SUS-codificados.

        Competência fechada/exportada → 409. Gated ``sus.write``.
        """
        competencia = self.get_object()
        try:
            summary = gerar_producao_ambulatorial(competencia, actor=request.user)
        except DjangoValidationError as exc:
            return Response({"detail": exc.messages[0]}, status=http_status.HTTP_409_CONFLICT)
        return Response(
            {"bpa_i_count": summary["bpa_i_count"], "total_valor": str(summary["total_valor"])},
            status=http_status.HTTP_200_OK,
        )

    @extend_schema(
        tags=["sus"],
        summary="Fecha a competência (aberta → fechada)",
        request=None,
        responses={200: SusCompetenciaSerializer},
    )
    @action(detail=True, methods=["post"], url_path="fechar")
    def fechar(self, request, pk=None):
        """Transição aberta → fechada. Já fechada/exportada → 409. Gated ``sus.write``."""
        competencia = self.get_object()
        try:
            competencia.fechar()
        except DjangoValidationError as exc:
            return Response({"detail": exc.messages[0]}, status=http_status.HTTP_409_CONFLICT)
        return Response(self.get_serializer(competencia).data, status=http_status.HTTP_200_OK)


@extend_schema_view(
    list=extend_schema(tags=["sus"], summary="Lista BPA-C", parameters=[_COMPETENCIA_PARAM]),
    create=extend_schema(tags=["sus"], summary="Cria BPA-C (entrada manual)"),
)
class BpaConsolidadoViewSet(_SusPermissionMixin, viewsets.ModelViewSet):
    """BPA-C (consolidado, sem paciente). Entrada manual. Read=sus.read / write=sus.write."""

    serializer_class = BpaConsolidadoSerializer

    def get_queryset(self):
        qs = BpaConsolidado.objects.all().order_by("-created_at")
        competencia = self.request.query_params.get("competencia")
        if competencia:
            qs = qs.filter(competencia_id=competencia)
        return qs


@extend_schema_view(
    list=extend_schema(tags=["sus"], summary="Lista BPA-I", parameters=[_COMPETENCIA_PARAM]),
)
class BpaIndividualizadoViewSet(_SusPermissionMixin, viewsets.ReadOnlyModelViewSet):
    """BPA-I (individualizado, com paciente). Read-only — gerado pelo bridge. Read=sus.read."""

    serializer_class = BpaIndividualizadoSerializer

    def get_queryset(self):
        qs = BpaIndividualizado.objects.all().order_by("-created_at")
        competencia = self.request.query_params.get("competencia")
        if competencia:
            qs = qs.filter(competencia_id=competencia)
        return qs
